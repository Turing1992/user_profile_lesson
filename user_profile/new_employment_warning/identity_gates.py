# 需要"泛称 + 场景"配对才成立的身份。
# 例："农民工"本身既可能是工人也可能是农民，必须配上具体劳动场景。
AMBIGUOUS_TERMS = {
    "工人": ["农民工", "打工", "务工", "工友"],
}

# 账号名带这些词说明账号主体是商家、机构或组织，不是个人从业者，
# 对**所有**身份一律否决。真实案例：
#   「AAA老鼠肉批发——张总」被判学生、「深圳市·正盈信科技·随州护士赵洲琪」被判医护、
#   「2013老兵基地」被判退役军人。
# 注意不要收录「律师事务所」「医院」这类本身就是职业资格证明的词。
GENERIC_BUSINESS_NAME_TERMS = [
    "批发", "总代", "代理", "加盟", "招商", "招聘", "货源", "微商",
    "旗舰店", "专卖", "门店", "商行", "商贸", "贸易", "店",
    "月子中心", "服务中心", "体验馆", "会所",
    "科技", "网络科技", "文化传媒", "传媒", "工作室", "俱乐部",
    "有限", "集团", "基地", "总部", "官方旗舰",
]


def _build_haystack(evidence, name, description, verified_reason, title, content):
    # type: (str, str, str, str, str, str) -> str
    """拼接归一化后的全量匹配文本。"""
    return _norm_text(" ".join(str(part or "") for part in (
        name, verified_reason, description, title, content, evidence,
    )))


def _profile_text(name, description, verified_reason):
    # type: (str, str, str) -> str
    """只含账号资料的归一化文本。"""
    return _norm_text(" ".join(str(part or "") for part in (
        name, verified_reason, description,
    )))


def _first_hit(haystack, terms):
    # type: (str, list) -> str
    """返回第一个命中的词，没有则返回空串。"""
    for term in terms:
        if _norm_text(term) in haystack:
            return term
    return ""


def passes_identity_gate(identity, evidence="", name="", description="",
                         verified_reason="", title="", content=""):
    # type: (str, str, str, str, str, str, str) -> tuple
    """检查某个身份是否通过专属硬门槛。

    Args:
        identity: 标准身份名。
        evidence: 模型给出的证据句。
        name: 账号名。
        description: 账号简介。
        verified_reason: 认证说明。
        title: 帖文标题。
        content: 帖文正文。

    Returns:
        tuple: ``(通过与否, 原因)``。通过时原因是命中的锚点词，
        未通过时是可读的拒绝理由。没有配置门槛的身份默认放行。
    """
    gate = IDENTITY_GATES.get(identity)
    if not gate:
        return True, "无门槛配置，放行"

    haystack = _build_haystack(
        evidence, name, description, verified_reason, title, content)
    if not haystack:
        return False, "无可用文本"

    # 1. 账号名是商家/机构/组织主体，对所有身份一律否决
    name_norm = _norm_text(name)
    generic_rejected = _first_hit(name_norm, GENERIC_BUSINESS_NAME_TERMS)
    if generic_rejected:
        return False, "账号名含商家/机构词[{}]".format(generic_rejected)

    # 2. 账号名是该身份领域的经营主体（如工人对应的「工程」「公司」）
    name_rejected = _first_hit(name_norm, gate.get("reject_in_name", []))
    if name_rejected:
        return False, "账号名含经营主体词[{}]".format(name_rejected)

    # 3. 否决词：账号资料或正文里命中即否决（同领域但不同角色）
    rejected = _first_hit(haystack, gate.get("reject_any", []))
    if rejected:
        return False, "命中否决词[{}]".format(rejected)

    # 4. 锚点词：必须命中至少一个
    anchor = _first_hit(haystack, gate.get("require_any", []))
    if not anchor:
        return False, "缺少{}的职业锚点词".format(identity)

    # 5. 歧义泛称：若锚点仅来自泛称，需要另有具体场景词支撑
    ambiguous = AMBIGUOUS_TERMS.get(identity)
    if ambiguous and _norm_text(anchor) in [_norm_text(t) for t in ambiguous]:
        concrete = [
            term for term in gate.get("require_any", [])
            if _norm_text(term) not in [_norm_text(t) for t in ambiguous]
        ]
        if not _first_hit(haystack, concrete):
            return False, "仅有泛称[{}]，缺少具体工作场景".format(anchor)

    return True, "命中锚点[{}]".format(anchor)
